using UnityEngine;

/// <summary>
/// **动作按钮**（区域位置识别的共享契约，2026-10-29）。
///
/// 背景：防御键这类**动作按钮**就压在敌人所在的画面区域上。
///   • 若一律“UI 优先”→ 玩家点敌人的手势会被按钮吞掉（教学直接跑不通）；
///   • 若一律“世界优先”→ 三选一 / 对话 / 结算这些**模态 UI** 又会漏（能在面板上打出去）。
///
/// 规则：**命中的是动作按钮，且该点下面有活着的敌人** → 这次点击**让给战斗**
/// （算攻击，不算点按钮）；其余情况一律按 UI 点击处理。
///
/// 放在数据层（<c>Locus.Data</c>）：输入层（<c>Locus.Flow</c>）与界面层（<c>Locus.UI</c>）都能看见它，
/// 彼此不产生反向依赖。
/// </summary>
public interface IActionButton
{
    /// <summary>
    /// 这次点击是否应该**让给战斗**（该点下面有活着的敌人 → 那一下是攻击，不是点按钮）。
    /// </summary>
    bool ShouldYieldToCombat(Vector2 screenPos);
}
